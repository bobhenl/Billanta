import { createHash, randomBytes } from "node:crypto";

/**
 * Public-API key format: `sk_live_<32 random base64url chars>`. The `sk_`
 * prefix (Stripe-style) is also how `CombinedAuthGuard`
 * (apps/backend/src/auth/combined-auth.guard.ts) tells an API-key bearer
 * token apart from a JWT without needing to attempt a lookup first.
 */
export const API_KEY_PREFIX = "sk_live_";

/**
 * Number of leading characters of the FULL key stored as `key_prefix`, for
 * UI identification only (e.g. showing "sk_live_ab12****" in the dashboard).
 * `API_KEY_PREFIX` itself is 8 chars, so this keeps 4 random chars visible —
 * enough to tell two keys apart in a list, nowhere near enough to help
 * reconstruct or brute-force the full secret.
 */
const STORED_PREFIX_LENGTH = 12;

/**
 * Generates a new plaintext API key. The caller is responsible for hashing
 * it (via {@link hashApiKey}) before persisting anything — this function
 * never touches the database and the returned `fullKey` must be shown to
 * the user exactly once (see `ApiKeysService.create`).
 */
export function generateApiKey(): { fullKey: string; keyPrefix: string } {
  // 24 random bytes -> 32 base64url characters (no padding), which is what
  // the "32 random chars" in the spec refers to.
  const randomPart = randomBytes(24).toString("base64url");
  const fullKey = `${API_KEY_PREFIX}${randomPart}`;
  return { fullKey, keyPrefix: fullKey.slice(0, STORED_PREFIX_LENGTH) };
}

/**
 * ============================================================================
 * WHY SHA-256, NOT bcrypt/argon2 — read before "fixing" this to use bcrypt.
 * ============================================================================
 * bcrypt/argon2/scrypt exist to slow down brute-forcing LOW-ENTROPY secrets a
 * human chose (passwords) — a slow, salted, adaptive hash makes guessing
 * "password123"-shaped inputs expensive even after a database leak. An API
 * key generated by {@link generateApiKey} is a 24-byte (192-bit) uniformly
 * random value the user never chooses and never types twice — there is
 * nothing to "guess" more cheaply by brute force than by generating and
 * hashing random 192-bit values yourself, which is already computationally
 * infeasible regardless of hash speed. Using a slow adaptive hash here would
 * only add latency to every single authenticated public-API request (every
 * call needs a hash-and-compare) for zero real security benefit.
 *
 * A second, more concrete reason: bcrypt's per-hash random salt means two
 * hashes of the SAME input differ, so looking a key up by hash requires
 * iterating every stored hash and calling `bcrypt.compare()` against each —
 * O(n) in the number of API keys that exist system-wide, on every request.
 * SHA-256 is deterministic, so `key_hash` can carry a normal unique index
 * (see `drizzle/schema.ts`) and be looked up in O(1) via a plain equality
 * WHERE clause (`find_active_api_key_by_hash` in rls-policies.sql) — the
 * same tradeoff GitHub, Stripe, and most other API-key issuers make for
 * exactly this reason.
 *
 * "Not reversible to plaintext" (see the spec / api-key.util.spec.ts) holds
 * here for the ordinary cryptographic-hash reason: SHA-256 is a one-way
 * function — there is no computationally feasible way to recover the
 * 192-bit random input from its digest, independent of hash speed. What
 * bcrypt buys over SHA-256 (slowing down *guessing* the input) is not a
 * relevant property for a high-entropy, machine-generated secret like this.
 */
export function hashApiKey(rawKey: string): string {
  return createHash("sha256").update(rawKey, "utf8").digest("hex");
}

/** Scope values a key can be created with. */
export const API_KEY_SCOPES = ["read", "write"] as const;

const SAFE_METHODS = new Set(["GET", "HEAD", "OPTIONS"]);

/**
 * Scope check for one request. A key with no scopes (every key created
 * before scopes were enforced) keeps full access; otherwise a key without
 * `write` (or a legacy `<resource>:write`) may only use safe methods.
 */
export function apiKeyAllowsMethod(scopes: readonly string[], method: string): boolean {
  if (scopes.length === 0) return true;
  if (scopes.some((scope) => scope === "write" || scope.endsWith(":write"))) return true;
  return SAFE_METHODS.has(method.toUpperCase());
}

/** True if `token` has the shape of an API key rather than a JWT. */
export function isApiKeyFormat(token: string): boolean {
  return token.startsWith(API_KEY_PREFIX);
}
