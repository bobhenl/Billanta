#!/usr/bin/env node
/**
 * LOCAL DEVELOPMENT ONLY. Gives you a working sign-in for the local stack:
 * generates a fresh random password for an existing local user (default
 * demo@faktur.local, the owner of the seeded "Demo s.r.o." tenant), stores
 * its bcrypt hash in the dev database and writes the plaintext to
 * `.env.dev-login` in the repo root — gitignored by the `.env.*` rule, so it
 * never reaches the repository.
 *
 *   node scripts/dev-login.mjs [email]
 *
 * Refuses to run unless DATABASE_URL points at localhost/127.0.0.1, so it
 * can never rotate a password on a real server by accident.
 */
import { randomBytes } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'apps/frontend/package.json'));
const bcrypt = require('bcryptjs');
const postgres = require('postgres');

const env = Object.fromEntries(
  readFileSync(join(root, '.env'), 'utf8')
    .split(/\r?\n/)
    .filter((line) => /^[A-Z_]+=/.test(line))
    .map((line) => [line.slice(0, line.indexOf('=')), line.slice(line.indexOf('=') + 1)])
);
const url = process.env.DATABASE_URL ?? env.DATABASE_URL;
if (!url || !/@(localhost|127\.0\.0\.1)[:/]/.test(url)) {
  console.error('Refusing: DATABASE_URL is not a localhost database.');
  process.exit(1);
}

const email = (process.argv[2] ?? 'demo@faktur.local').toLowerCase();
const password = randomBytes(12).toString('base64url');
const sql = postgres(url, { max: 1 });
const rows = await sql`
  UPDATE users SET password_hash = ${await bcrypt.hash(password, 12)}, updated_at = now()
  WHERE email = ${email} RETURNING id`;
await sql.end();

if (rows.length === 0) {
  console.error(`No local user ${email}. Sign up at http://localhost:3100/cs/signup first.`);
  process.exit(1);
}

writeFileSync(
  join(root, '.env.dev-login'),
  `# Local dev sign-in, generated by scripts/dev-login.mjs. Gitignored.\nDEV_LOGIN_EMAIL=${email}\nDEV_LOGIN_PASSWORD=${password}\n`
);
console.log(`Password for ${email} rotated; credentials written to .env.dev-login`);
